"""Regenerate lib/features/route_rules/notifier/rkn_ru_domains.dart for A-VPN.

Everything outside .ru/.su/.рф already goes through the VPN, so the only blocked sites the routing has
to know about are the ones in those zones. Source: the curated antifilter community list.
Usage: python gen_rkn_domains.py <hiddify repo dir>
"""
import re
import sys
import urllib.request

SOURCE = "https://community.antifilter.download/list/domains.lst"
ZONE = re.compile(r"(^|\.)(ru|su|xn--p1ai)$")


def normalize_domain(line):
    domain = line.strip().lower().removeprefix("*.").lstrip(".")
    if not domain or domain.startswith("#"):
        return None
    try:
        domain = domain.encode("idna").decode("ascii")
    except UnicodeError:
        return None
    if len(domain) > 253 or not all(re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", label) for label in domain.split(".")):
        return None
    return domain.removeprefix("www.")


def main(repo):
    text = urllib.request.urlopen(SOURCE, timeout=60).read().decode("utf-8")
    domains = set()
    for line in text.splitlines():
        d = normalize_domain(line)
        if not d or not ZONE.search(d):
            continue
        domains.add(d[4:] if d.startswith("www.") else d)
    body = "".join(f"  '{d}',\n" for d in sorted(domains))
    out = (
        "// GENERATED by gen_rkn_domains.py from the antifilter community list; do not edit by hand.\n\n"
        "/// Sites in the .ru, .su and .рф zones blocked in Russia. They go through the VPN even though\n"
        "/// those zones otherwise go direct.\n"
        f"const rknRuDomains = [\n{body}];\n"
    )
    path = f"{repo}/lib/features/route_rules/notifier/rkn_ru_domains.dart"
    with open(path, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(out)
    print(f"{len(domains)} domains -> {path}")


if __name__ == "__main__":
    main(sys.argv[1])
