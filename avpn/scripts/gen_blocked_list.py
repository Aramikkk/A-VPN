"""Regenerate lib/features/route_rules/notifier/blocked_list.dart for A-VPN.

"Only blocked through the VPN" mode: these domains and IP ranges go through the VPN, everything else goes
direct. Source: itdoginfo/allow-domains ("Russia inside": resources blocked in Russia, plus the IP ranges of
Telegram, Meta, Twitter and Discord, whose apps often connect by IP), and a few additions it lacks.
Usage: python gen_blocked_list.py <hiddify repo dir>
"""
import ipaddress
import sys
import urllib.request

BASE = "https://raw.githubusercontent.com/itdoginfo/allow-domains/main/"
DOMAINS = "Russia/inside-raw.lst"
SUBNETS = ["Subnets/IPv4/telegram.lst", "Subnets/IPv4/meta.lst", "Subnets/IPv4/twitter.lst", "Subnets/IPv4/discord.lst"]

# blocked or throttled services the list leaves out (it routes Telegram by IP only)
EXTRA_DOMAINS = [
    "telegram.org", "telegram.me", "t.me", "telesco.pe", "tdesktop.com", "telegra.ph", "telegram.dog",
    "cdn-telegram.org", "whatsapp.com", "whatsapp.net", "wa.me", "x.com", "twitter.com", "twimg.com", "t.co",
]


def fetch(path):
    return urllib.request.urlopen(BASE + path, timeout=60).read().decode("utf-8")


def main(repo):
    domains = set(EXTRA_DOMAINS)
    for line in fetch(DOMAINS).splitlines():
        d = line.strip().lower().lstrip(".")
        if not d or d.startswith("#"):
            continue
        d = d.encode("idna").decode("ascii")
        domains.add(d[4:] if d.startswith("www.") else d)
    cidrs = set()
    for path in SUBNETS:
        for line in fetch(path).splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                cidrs.add(str(ipaddress.ip_network(line, strict=False)))
    body_d = "".join(f"  '{d}',\n" for d in sorted(domains))
    body_c = "".join(f"  '{c}',\n" for c in sorted(cidrs, key=lambda c: ipaddress.ip_network(c)))
    out = (
        "// GENERATED by avpn/scripts/gen_blocked_list.py from itdoginfo/allow-domains; do not edit by hand.\n\n"
        "/// Domains blocked in Russia (and their subdomains): through the VPN in the \"only blocked\" mode.\n"
        f"const blockedDomains = [\n{body_d}];\n\n"
        "/// IP ranges of Telegram, Meta, Twitter and Discord, whose apps often connect by address.\n"
        f"const blockedCidrs = [\n{body_c}];\n"
    )
    path = f"{repo}/lib/features/route_rules/notifier/blocked_list.dart"
    open(path, "w", encoding="utf-8", newline="\n").write(out)
    print(f"{len(domains)} domains, {len(cidrs)} ranges -> {path}")


if __name__ == "__main__":
    main(sys.argv[1])
